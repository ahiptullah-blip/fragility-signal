"""Label report and sanity checks -> docs/labels_report.md.

Run: python3 -m src.labels.report
Uses quarter-end scoring dates from 2012-06-30 to the last quarter end before DATA_END.
"""
from __future__ import annotations

import re

import numpy as np
import pandas as pd

from src.ingest.sec_http import ROOT
from src.labels.build_events import acc_url, fetch_text, has_items
from src.labels.labels import DATA_END, label, label_panel, load_events
from src.universe.universe import load_10k_table, universe_as_of

OUT = ROOT / "docs" / "labels_report.md"
INTERIM = ROOT / "data" / "interim"
SEED = 20261108


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main() -> None:
    ev = load_events()
    tk = load_10k_table()
    co = pd.read_csv(INTERIM / "companies.csv", dtype={"cik": str}).set_index("cik")["name"]
    t1 = ev[ev.tier == 1].rename(columns={"entity_id": "cik"})[["cik", "event_date"]]
    ufn = lambda d: universe_as_of(d, tk, t1)  # noqa: E731
    dates = pd.date_range("2012-06-30", DATA_END, freq="QE")
    panel = label_panel(dates, ufn)
    panel_t1 = label_panel(dates, ufn, windows=(12,), tiers=(1,))
    panel["label_12m_t1only"] = panel_t1["label_12m"].values
    panel["year"] = panel.as_of.dt.year
    panel.to_csv(INTERIM / "label_panel.csv.gz", index=False)
    out = ["# Labels Report (Prompt 3)", "",
           f"Generated by `src/labels/report.py`. Data end: {DATA_END.date()}. Scoring dates: "
           f"quarter ends {dates[0].date()} to {dates[-1].date()} ({len(dates)} dates).",
           "Positive label = Tier 1 or Tier 2 event in the window (draft, pending freeze).", ""]

    # ---- Step 2 summary
    ever = panel.entity_id.unique()
    evu = ev[ev.entity_id.isin(ever)]
    out += ["## Event table summary", "",
            f"- Events in src/labels/events.csv: **{len(ev)}** across {ev.entity_id.nunique()} entities "
            f"(all entities that were ever eligible, events from 2009).",
            f"- Entities ever in the universe (2012-06-30 onward): **{len(ever)}**.",
            f"- Of those, entities with **no event of any tier**: **{len(set(ever) - set(evu.entity_id))}**; "
            f"with no Tier 1 or Tier 2 event: **{len(set(ever) - set(evu[evu.tier <= 2].entity_id))}**.", ""]
    by_type = ev.groupby(["tier", "event_type"]).size().rename("events").reset_index()
    by_type["entities"] = ev.groupby(["tier", "event_type"]).entity_id.nunique().values
    by_type["high / medium / low confidence"] = [
        " / ".join(str(((ev.event_type == t) & (ev.confidence == c)).sum()) for c in ("high", "medium", "low"))
        for t in by_type.event_type]
    out += ["### Events per tier and type", "", md(by_type), ""]
    ev["year"] = pd.to_datetime(ev.event_date).dt.year
    py = ev.pivot_table(index="year", columns="tier", values="entity_id", aggfunc="count", fill_value=0)
    py.columns = [f"Tier {c}" for c in py.columns]
    out += ["### Events per year (all entities in the table)", "", md(py.reset_index()), ""]

    # ---- scorable events and the kill gate
    pos = panel[panel.label_12m == 1]
    scorable = pos.drop_duplicates(["entity_id", "next_event_date"])
    out += ["## Scorable positive events (kill gate)", "",
            "An event is scorable if the entity was in the universe on at least one scoring date in "
            "the 12 months before it. Events at companies below the $50M float floor, or outside "
            "the niche at the time, are in the table but can never produce a positive label.", "",
            f"- Distinct scorable Tier 1 + Tier 2 events: **{len(scorable)}** at "
            f"**{scorable.entity_id.nunique()}** entities.",
            f"- Tier 1 only: **{panel[panel.label_12m_t1only == 1].entity_id.nunique()}** entities.",
            f"- Kill gate (at least 50 labeled events): "
            f"**{'PASS' if len(scorable) >= 50 else 'FAIL'}**.", "",
            md(scorable.next_event_type.value_counts().rename_axis("event_type").reset_index(name="scorable events")), ""]

    # ---- base rate by year
    g = panel.groupby("year")
    br = pd.DataFrame({
        "entity-quarters": g.size(),
        "avg universe size": (g.size() / g.as_of.nunique()).round(0).astype(int),
        "positives 12m": g.label_12m.sum(),
        "base rate 6m": (g.label_6m.mean() * 100).round(2),
        "base rate 12m": (g.label_12m.mean() * 100).round(2),
        "base rate 24m": (g.label_24m.mean() * 100).round(2),
        "base rate 12m (Tier 1 only)": (g.label_12m_t1only.mean() * 100).round(2),
        "12m censored": g.censored_12m.mean().map(lambda x: "all" if x == 1 else ("part" if x > 0 else "")),
    }).reset_index()
    uncensored = panel[~panel.censored_12m]
    out += ["## Base rate by year (Step 4)", "",
            "Base rate = share of entity-quarters with a positive label (percent). Censored windows "
            "(extending past the data end) are marked; their zeros are not confirmed negatives "
            "and their rates are lower bounds.", "", md(br), "",
            f"Pooled uncensored 12-month base rate: **{uncensored.label_12m.mean() * 100:.2f}%** "
            f"({int(uncensored.label_12m.sum())} positive of {len(uncensored)} entity-quarters).", ""]

    # ---- spot checks
    f = pd.read_csv(INTERIM / "filings.csv.gz", dtype={"cik": str, "items": str},
                    parse_dates=["filing_date"])
    rng = np.random.default_rng(SEED)
    psample = uncensored[uncensored.label_12m == 1].sample(10, random_state=SEED)
    nsample = uncensored[uncensored.label_12m == 0].sample(10, random_state=SEED + 1)
    out += ["## Spot check: 10 random positives", "",
            "Each row: the scoring date, the event that made it positive, and the evidence text "
            "pulled from the source filing.", ""]
    for r in psample.itertuples():
        lab = label(r.entity_id, r.as_of, 12)
        e = ev[(ev.entity_id == r.entity_id) & (pd.to_datetime(ev.event_date) == lab.event_date)].iloc[0]
        out += [f"- **{co.get(r.entity_id, r.entity_id)}** (CIK {r.entity_id}), scored {r.as_of.date()}: "
                f"{e.event_type} on {e.event_date} ({e.confidence}). Evidence: {e.notes[:260]}. "
                f"Source: {e.source_url}"]
    out += ["", "## Spot check: 10 random negatives", "",
            "Each row: what the company filed during the 12-month window. A clean negative shows "
            "continued periodic reporting and none of the event-bearing filings.", ""]
    for r in nsample.itertuples():
        w = f[(f.cik == r.entity_id) & (f.filing_date > r.as_of)
              & (f.filing_date <= r.as_of + pd.DateOffset(months=12))]
        periodic = w.form.isin(["10-K", "10-Q"]).sum()
        flags = {c: int(w["items"].apply(lambda s: has_items(s, c)).sum()) for c in ("1.03", "2.04", "2.05", "3.01")}
        other = {k: int((w.form.isin(v)).sum()) for k, v in
                 {"25-NSE": ["25-NSE"], "Form 15": ["15-12B", "15-12G", "15-15D"]}.items()}
        nxt = ev[(ev.entity_id == r.entity_id) & (pd.to_datetime(ev.event_date) > r.as_of)]
        nxt_s = f"; next event of any tier: {nxt.iloc[0].event_type} {nxt.iloc[0].event_date}" if len(nxt) else "; no later event"
        out += [f"- **{co.get(r.entity_id, r.entity_id)}** (CIK {r.entity_id}), scored {r.as_of.date()}: "
                f"{periodic} 10-K/10-Q filed in window; 8-K items 1.03/2.04/2.05/3.01 = "
                f"{flags['1.03']}/{flags['2.04']}/{flags['2.05']}/{flags['3.01']}; "
                f"25-NSE {other['25-NSE']}, Form 15 {other['Form 15']}{nxt_s}."]

    # ---- date uncertainty
    unc = ev[ev.date_uncertainty_days > 90].copy()
    unc["name"] = unc.entity_id.map(co)
    out += ["", "## Events with date uncertainty above 90 days", "",
            "Spread between candidate dates for the same event (for example, the 8-K report date "
            "vs filing date, or the first exchange notice vs the Form 25-NSE).", ""]
    out += [md(unc[["name", "entity_id", "event_type", "event_date", "date_uncertainty_days", "notes"]])
            if len(unc) else "None."]

    # ---- silent exits
    last_periodic = f[f.form.isin(["10-K", "10-Q"])].groupby("cik").filing_date.max()
    gone = last_periodic[last_periodic < DATA_END - pd.Timedelta(days=548)]
    gone = gone[gone.index.isin(ever)]
    merger = f[f.form.isin(["DEFM14A", "PREM14A", "SC 14D9", "SC TO-T", "SC 13E3", "25-NSE"])
               | f["items"].apply(lambda s: has_items(s, "5.01") or has_items(s, "2.01"))]
    silent = [c for c in gone.index
              if c not in set(ev[ev.tier == 1].entity_id)
              and not ((merger.cik == c) & (merger.filing_date >= gone[c] - pd.Timedelta(days=400))).any()]
    out += ["", "## Silent exits (label-quality risk)", "",
            f"Entities ever in the universe that stopped filing 10-K/10-Q more than 18 months before "
            f"the data end: **{len(gone)}**. Of those, **{len(silent)}** have no Tier 1 event and no "
            f"merger or delisting filing around their exit. These could be missed collapses:", ""]
    out += [f"- {co.get(c, c)} (CIK {c}), last 10-K/10-Q {gone[c].date()}" for c in silent[:40]]
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
